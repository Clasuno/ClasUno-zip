-- Aprobar / rechazar profes (solo administradores)
create or replace function public.set_teacher_status(teacher uuid, nuevo text) returns void language plpgsql security definer set search_path = '' as $$
begin
  if not private.es_admin() then raise exception 'Solo administradores'; end if;
  if nuevo not in ('pending', 'approved', 'rejected', 'paused') then raise exception 'Estado no válido'; end if;
  update public.teacher_profiles set status = nuevo, verified = (nuevo = 'approved') or verified where user_id = teacher;
end $$;
revoke all on function public.set_teacher_status(uuid, text) from public, anon;
grant execute on function public.set_teacher_status(uuid, text) to authenticated;

-- ---------- Profes aprobados para la web pública ----------
create or replace function public.profes_publicos() returns jsonb language sql stable security definer set search_path = '' as $$
  select coalesce(jsonb_agg(jsonb_build_object(
    'id', t.user_id, 'nombre', trim(p.first_name || ' ' || p.last_name), 'avatar', p.avatar_url,
    'degree', t.degree, 'center', t.center, 'headline', t.headline, 'description', t.description,
    'modality', t.modality, 'zone', t.zone, 'price', t.price_per_hour,
    'classes', t.classes_count, 'positive', t.positive_reviews, 'verified', t.verified,
    'certificado', t.certificado, 'grupos', t.acepta_grupos,
    'languages', to_jsonb(t.languages), 'availability', to_jsonb(t.availability), 'experience', t.experience_years,
    'subjects', (select coalesce(jsonb_agg(s.name), '[]'::jsonb) from public.teacher_subjects ts join public.subjects s on s.id = ts.subject_id where ts.teacher_id = t.user_id),
    'levels',   (select coalesce(jsonb_agg(l.name order by l.sort_order), '[]'::jsonb) from public.teacher_levels tl join public.levels l on l.id = tl.level_id where tl.teacher_id = t.user_id)
  )), '[]'::jsonb)
  from public.teacher_profiles t join public.profiles p on p.id = t.user_id
  where t.status = 'approved';
$$;
revoke all on function public.profes_publicos() from public;
grant execute on function public.profes_publicos() to anon, authenticated;

-- Guardar el perfil del profe desde el alta (con los permisos del propio profe)
create or replace function public.guardar_perfil_profe(datos jsonb, asignaturas text[], niveles text[]) returns void
language plpgsql security invoker set search_path = '' as $$
declare r public.teacher_profiles;
begin
  if auth.uid() is null then raise exception 'Hace falta iniciar sesión'; end if;
  r := jsonb_populate_record(null::public.teacher_profiles, datos);
  insert into public.teacher_profiles (user_id, degree, center, headline, description, modality, zone, price_per_hour, availability, languages, acepta_grupos)
  values (auth.uid(), r.degree, r.center, r.headline, r.description, coalesce(r.modality, 'ambas'), r.zone, r.price_per_hour, coalesce(r.availability, '{}'), coalesce(r.languages, array['Español']), coalesce(r.acepta_grupos, false))
  on conflict (user_id) do update set degree = excluded.degree, center = excluded.center, headline = excluded.headline, description = excluded.description,
    modality = excluded.modality, zone = excluded.zone, price_per_hour = excluded.price_per_hour, availability = excluded.availability,
    languages = excluded.languages, acepta_grupos = excluded.acepta_grupos;
  delete from public.teacher_subjects where teacher_id = auth.uid();
  insert into public.teacher_subjects (teacher_id, subject_id) select auth.uid(), s.id from public.subjects s where s.name = any (asignaturas);
  delete from public.teacher_levels where teacher_id = auth.uid();
  insert into public.teacher_levels (teacher_id, level_id) select auth.uid(), l.id from public.levels l where l.name = any (niveles);
end $$;
revoke all on function public.guardar_perfil_profe(jsonb, text[], text[]) from public, anon;
grant execute on function public.guardar_perfil_profe(jsonb, text[], text[]) to authenticated;

