-- Nadie puede hacerse admin ni cambiarse de rol desde la web
create or replace function private.proteger_perfil() returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if coalesce(current_setting('request.jwt.claim.role', true), '') <> 'service_role' and session_user <> 'postgres' then
    new.is_admin := old.is_admin; new.role := old.role; new.id := old.id;
  end if;
  return new;
end $$;
create trigger proteger_perfil before update on public.profiles for each row execute function private.proteger_perfil();

create or replace function private.crear_perfil() returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles (id, role, first_name, last_name)
  values (new.id,
          case when new.raw_user_meta_data ->> 'role' = 'teacher' then 'teacher' else 'student' end,
          left(coalesce(new.raw_user_meta_data ->> 'first_name', ''), 60),
          left(coalesce(new.raw_user_meta_data ->> 'last_name', ''), 80));
  return new;
end $$;
create trigger crear_perfil after insert on auth.users for each row execute function private.crear_perfil();

create or replace function private.es_admin() returns boolean language sql stable security definer set search_path = '' as $$
  select coalesce((select is_admin from public.profiles where id = auth.uid()), false);
$$;

