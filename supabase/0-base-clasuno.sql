-- El profe no puede aprobarse, verificarse ni tocar sus contadores. Si cambia sus estudios, vuelve a revisión.
create or replace function private.proteger_profe() returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if private.es_admin() or coalesce(current_setting('request.jwt.claim.role', true), '') = 'service_role' or session_user = 'postgres' then
    new.updated_at := now(); return new;
  end if;
  if tg_op = 'INSERT' then
    new.status := 'pending'; new.verified := false; new.certificado := false; new.classes_count := 0; new.positive_reviews := 0;
  else
    new.verified := old.verified; new.certificado := old.certificado; new.classes_count := old.classes_count; new.positive_reviews := old.positive_reviews;
    new.status := case when old.status = 'approved' and (new.degree is distinct from old.degree or new.center is distinct from old.center) then 'pending'
                       when new.status = 'paused' and old.status = 'approved' then 'paused'
                       when new.status = 'approved' and old.status = 'paused' then 'approved'
                       else old.status end;
  end if;
  new.updated_at := now();
  return new;
end $$;
create trigger proteger_profe before insert or update on public.teacher_profiles for each row execute function private.proteger_profe();

